"""A quiet reading surface with a persistent, clearly grouped player."""
import tkinter as tk
from tkinter import ttk

BG = '#f2f4f1'
PAPER = '#fffefb'
INK = '#213c35'
MUTED = '#63766e'
ACCENT = '#245e4d'


def build_reader(r, help_menu, voices):
    root = r.root
    root.title('Talevoxa — Your books, read aloud')
    root.geometry('1020x780')
    root.minsize(720, 550)
    root.configure(bg=BG)
    style = ttk.Style(root)
    style.theme_use('clam')
    style.configure('.', font=('Segoe UI', 10), background=BG, foreground=INK)
    style.configure('TFrame', background=BG)
    style.configure('TLabel', background=BG, foreground=INK)
    style.configure('Muted.TLabel', foreground=MUTED)
    style.configure('Brand.TLabel', font=('Georgia', 25), foreground=ACCENT)
    style.configure('Book.TLabel', font=('Segoe UI Semibold', 14))
    style.configure('TButton', padding=(10, 7), background='#e6ece6', borderwidth=0, foreground=INK)
    style.map('TButton', background=[('active', '#d6e2d8'), ('pressed', '#c6d8ce')], foreground=[('disabled', '#84918a')])
    style.configure('Primary.TButton', background=ACCENT, foreground='white', padding=(22, 9), font=('Segoe UI Semibold', 11))
    style.map('Primary.TButton', background=[('disabled', '#cdd8d1'), ('active', '#194838')], foreground=[('disabled', '#6b7d73')])
    style.configure('Quiet.TButton', background=BG, padding=(8, 6))
    style.configure('TCombobox', padding=5, fieldbackground=PAPER, arrowsize=13)
    style.map('TCombobox', fieldbackground=[('readonly', PAPER)], selectbackground=[('readonly', PAPER)], selectforeground=[('readonly', INK)])
    style.configure('TSpinbox', padding=4, fieldbackground=PAPER)
    style.configure('TCheckbutton', background=BG, font=('Segoe UI', 9))
    style.map('TCheckbutton', background=[('active', BG)])
    style.configure('Horizontal.TScale', background=BG, troughcolor='#dce4dd', borderwidth=0)
    style.configure('Treeview', rowheight=32, background=PAPER, fieldbackground=PAPER, borderwidth=0, font=('Segoe UI', 10))
    style.configure('Treeview.Heading', font=('Segoe UI Semibold', 10), padding=8)
    style.map('Treeview', background=[('selected', '#d7e8dc')], foreground=[('selected', INK)])

    shell = ttk.Frame(root, padding=(22, 16))
    shell.pack(fill='both', expand=True)
    shell.columnconfigure(0, weight=1)
    shell.rowconfigure(3, weight=1)
    header = ttk.Frame(shell)
    header.grid(row=0, column=0, sticky='ew', pady=(0, 14))
    ttk.Label(header, text='Talevoxa', style='Brand.TLabel').pack(side='left')
    r.update_button = ttk.Button(header, text='Check updates', style='Quiet.TButton', command=r.update_action)
    r.update_button.pack(side='right')
    r.open_button = ttk.Button(header, text='Open a book', command=r.open_book)
    r.open_button.pack(side='right', padx=10)
    ttk.Button(header, text='Bookshelf', style='Quiet.TButton', command=r.show_bookshelf).pack(side='right')

    book = ttk.Frame(shell)
    book.grid(row=1, column=0, sticky='ew', pady=(0, 12))
    book.columnconfigure(0, weight=1)
    ttk.Label(book, text='YOUR READING SPACE', style='Muted.TLabel', font=('Segoe UI', 9)).grid(row=0, column=0, sticky='w')
    r.title = ttk.Label(book, text='A little time for a good book', style='Book.TLabel')
    r.title.grid(row=1, column=0, sticky='ew')
    ttk.Button(book, text='Bookmarks', style='Quiet.TButton', command=r.show_bookmarks).grid(row=0, column=1, rowspan=2, sticky='e')

    narrator = ttk.Frame(shell)
    narrator.grid(row=2, column=0, sticky='ew', pady=(0, 12))
    narrator.columnconfigure(1, weight=1)
    ttk.Label(narrator, text='Narrator', style='Muted.TLabel').grid(row=0, column=0, padx=(0, 10))
    r.voice = ttk.Combobox(narrator, values=list(voices), state='readonly', width=24)
    r.voice.current(0)
    r.update_voice_choices()
    r.voice.grid(row=0, column=1, sticky='ew')
    r.preview = ttk.Button(narrator, text='Preview', style='Quiet.TButton', command=lambda: r.start(True))
    r.preview.grid(row=0, column=2, padx=6)
    ttk.Button(narrator, text='More voices / downloads', command=r.show_voices).grid(row=0, column=3)

    paper = tk.Frame(shell, bg=PAPER, highlightbackground='#dce3da', highlightthickness=1)
    paper.grid(row=3, column=0, sticky='nsew')
    paper.columnconfigure(0, weight=1)
    paper.rowconfigure(1, weight=1)
    chapters = ttk.Frame(paper, padding=(10, 8))
    chapters.grid(row=0, column=0, columnspan=2, sticky='ew')
    chapters.columnconfigure(1, weight=1)
    r.chapter_back = ttk.Button(chapters, text='‹ Chapter', style='Quiet.TButton', command=lambda: r.move_chapter(-1))
    r.chapter_back.grid(row=0, column=0)
    r.chapter_picker = ttk.Combobox(chapters, state='disabled', width=14)
    r.chapter_picker.grid(row=0, column=1, sticky='ew', padx=8)
    r.chapter_picker.bind('<<ComboboxSelected>>', r.select_chapter)
    r.chapter_next = ttk.Button(chapters, text='Chapter ›', style='Quiet.TButton', command=lambda: r.move_chapter(1))
    r.chapter_next.grid(row=0, column=2)
    size = r.preferences.get('reading_font_size', 17)
    r.reading_font_size = max(14, min(26, size)) if isinstance(size, int) else 17
    r.text = tk.Text(paper, height=3, width=20, wrap='word', font=('Georgia', r.reading_font_size), bg=PAPER, fg=INK,
                     relief='flat', borderwidth=0, padx=26, pady=22, spacing1=3, spacing3=10, selectbackground='#d5e5d6')
    r.text.grid(row=1, column=0, sticky='nsew')
    scrollbar = ttk.Scrollbar(paper, command=r.text.yview)
    scrollbar.grid(row=1, column=1, sticky='ns', padx=(0, 4), pady=8)
    r.text.configure(yscrollcommand=scrollbar.set)
    r.show_text('Your next chapter starts here.\n\nOpen a book, choose a narrator, and settle in.\n\nWord · EPUB · PDF · TXT\n\nYour place is saved automatically. Press Ctrl+B to keep a favourite moment.')

    player = ttk.Frame(shell)
    player.grid(row=4, column=0, sticky='ew', pady=(12, 0))
    player.columnconfigure(0, weight=1)
    timeline = ttk.Frame(player)
    timeline.grid(row=0, column=0, sticky='ew')
    r.position = ttk.Label(timeline, text='No book open', style='Muted.TLabel')
    r.position.pack(side='left')
    r.seek = ttk.Scale(timeline, from_=0, to=1)
    r.seek.pack(side='left', fill='x', expand=True, padx=(12, 0))
    r.seek.bind('<ButtonRelease-1>', r.seek_in_chapter)
    r.seek.bind('<ButtonPress-1>', lambda e: setattr(r, 'seeking', True))
    controls = ttk.Frame(player)
    controls.grid(row=1, column=0, sticky='ew', pady=8)
    r.back = ttk.Button(controls, text='Previous', style='Quiet.TButton', command=lambda: r.move(-1))
    r.back.pack(side='left')
    ttk.Button(controls, text='↶ 15s', style='Quiet.TButton', command=r.rewind).pack(side='left', padx=4)
    r.play = ttk.Button(controls, text='Play', style='Primary.TButton', command=r.start)
    r.play.pack(side='left', padx=4)
    r.pause = ttk.Button(controls, text='Pause', command=r.toggle_pause)
    r.pause.pack(side='left', padx=4)
    ttk.Button(controls, text='Stop', style='Quiet.TButton', command=r.stop).pack(side='left', padx=4)
    r.next = ttk.Button(controls, text='Next', style='Quiet.TButton', command=lambda: r.move(1))
    r.next.pack(side='left')
    r.speed = tk.DoubleVar(value=1)
    r.speed.trace_add('write', r.change_speed)
    ttk.Spinbox(controls, from_=0.5, to=2, increment=0.1, textvariable=r.speed, width=4).pack(side='right')
    ttk.Label(controls, text='Speed', style='Muted.TLabel').pack(side='right', padx=8)
    options = ttk.Frame(player)
    options.grid(row=2, column=0, sticky='ew')
    r.chapter_only = tk.BooleanVar(value=False)
    r.chapter_option = ttk.Checkbutton(options, text='Stop after chapter', variable=r.chapter_only)
    r.chapter_option.pack(side='left')
    ttk.Label(options, text='Sleep', style='Muted.TLabel').pack(side='left', padx=(16, 6))
    r.sleep_choice = ttk.Combobox(options, values=['Off', '15 minutes', '30 minutes', '60 minutes'], state='readonly', width=10)
    r.sleep_choice.current(0)
    r.sleep_choice.pack(side='left')
    r.sleep_choice.bind('<<ComboboxSelected>>', r.set_sleep_timer)
    ttk.Button(options, text='A+', style='Quiet.TButton', width=3, command=lambda: change_font(r, 1)).pack(side='right')
    ttk.Button(options, text='A−', style='Quiet.TButton', width=3, command=lambda: change_font(r, -1)).pack(side='right', padx=4)
    r.smooth = tk.BooleanVar(value=False)
    help_menu.add_checkbutton(label='Extra buffering for slower PCs', variable=r.smooth)
    r.clean_pdf = tk.BooleanVar(value=True)
    help_menu.add_checkbutton(label='Remove repeated PDF headers and page numbers', variable=r.clean_pdf)
    r.status = ttk.Label(shell, text='Private listening · Free voices · Your books stay on this PC', style='Muted.TLabel', font=('Segoe UI', 9))
    r.status.grid(row=5, column=0, sticky='ew', pady=(8, 0))

    r.reading_panels = (book, narrator, paper, player)
    r.build_bookshelf(shell)
    r.show_bookshelf()

    def resized(event):
        if event.widget == root:
            r.title.configure(wraplength=max(220, event.width - 210))
            r.status.configure(wraplength=max(300, event.width - 50))
    root.bind('<Configure>', resized, add='+')


def change_font(reader, delta):
    reader.reading_font_size = max(14, min(26, reader.reading_font_size + delta))
    reader.text.configure(font=('Georgia', reader.reading_font_size))
    reader.preferences['reading_font_size'] = reader.reading_font_size
    reader.save_preferences()
